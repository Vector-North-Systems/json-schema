package com.vectornorthsystems.samples

import com.vectornorthsystems.jsonschema.*
import io.ktor.client.*
import io.ktor.client.engine.java.*
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json

/**
 * The simplest case: @SchemaRoot makes the processor .com.vectornorthsystems.samples.generate `getSimpleBookSchema()`.
 * Both properties have no default value and are not nullable, so both are required.
 */
@SchemaRoot
data class SimpleBook(
    val title: String,
    val author: String
)

/**
 * A property with a default value is optional: it is left out of the schema's `required` list.
 */
@SchemaRoot
data class AnonymousBook(
    val title: String,
    // A default value makes the property optional.
    val author: String = "Anonymous"
)

/**
 * [SchemaRequired] overrides the rule above: the property has a default value but is still listed as required.
 */
@SchemaRoot
data class AnonymousBookRequired(
    val title: String,
    // A default value makes the property optional, yet the annotation forces it to be required.
    @SchemaRequired
    val author: String = "Anonymous"
)

/**
 * A nullable type becomes a schema type that also accepts `null`. The property has no default value, so it is
 * still required: the model must send the key, and its value may be `null`.
 */
@SchemaRoot
data class BookNullable(
    val title: String?,
)

/**
 * A nullable property with a default value is optional. [SchemaRequired] makes it required, so the model must
 * always send the key, with either a value or `null`.
 */
@SchemaRoot
data class SimpleBoardGameNullableRequired(
    @SchemaRequired
    val name: String? = null,
)

/**
 * A tag of a [Book]. The description tells the model what to put in the property.
 */
@Serializable
data class BookTags(
    @SchemaDescription("Tags that can be applied to a book, for example: Fiction, History, Programming, etc")
    val name: String,
)

/**
 * Shows the constraint annotations, and a nested class ([BookTags]) inside a list.
 */
@Serializable
data class Book(
    @SchemaDescription("The title of the book")
    val title: String,

    // At most 3 authors.
    @SchemaMaxItems(3)
    val authors: List<String> = emptyList(),

    // Required despite the default value, with at most 5 tags.
    @SchemaRequired
    @SchemaMaxItems(5)
    val tags: List<BookTags> = emptyList(),

    // Between 1.0 and 5.0 when known. Optional, so the model can leave it out for a book without a rating.
    @SchemaMinimum(1.0)
    @SchemaMaximum(5.0)
    val rating: Double? = null,
)

/**
 * The root used by main(). Its schema references [Book], which needs no @SchemaRoot of its own: the processor
 * follows property types, including the elements of a list.
 *
 * [Serializable] is all the decoding needs: the schema and the decoder both come from these classes, so they always
 * agree.
 */
@Serializable
@SchemaRoot
data class Library(
    val books: List<Book>,
)

/**
 * An example of the whole round trip with Gemini structured output: main() sends the schema of [.com.vectornorthsystems.samples.Library] as the
 * response format, and decodes the reply straight back into a [.com.vectornorthsystems.samples.Library].
 *
 * Run it with a Gemini API key:
 *   GEMINI_API_KEY=... ./gradlew :json-schema-tests:run
 *
 * Then try changing the classes. For example, add this to [Book] and run again:
 *
 *   @SchemaDescription("The year the book was first published")
 *   val yearPublished: Int? = null,
 *
 * The schema, the request and the decoding all follow, with no other code to change.
 *
 * The classes below, from the simplest to the one used in main(), show what the annotations do. Fixtures that the
 * tests check belong in the `fixtures` package instead.
 */
suspend fun classifyLibrary() {
    // Generated by the processor from the @SchemaRoot annotation on .com.vectornorthsystems.samples.Library.
    println("The .com.vectornorthsystems.samples.Library class JSON schema is: ${getLibrarySchema()}")

    val input = """
        Let's classify the following books:
        Brave New World is a dystopian science fiction novel by Aldous Huxley. It has a rating of 3.98 on Goodreads.com.
        The Odyssey tells the story of Odysseus's return to Ithaca after the Trojan War. It is a classic of fiction by Homer. Among its many translations, the English version by Robert Fagles is rated 3.86 on Goodreads.com.
        The Metamorphosis is a story by Franz Kafka, in which the fictional Gregor Samsa wakes one morning from a dream to find himself transformed into a gigantic insect.
    """.trimIndent()

    // use {} closes the client when done, so the JVM can exit.
    val library: Library = HttpClient(Java).use { client ->
        // The schema goes out and the answer comes back as a .com.vectornorthsystems.samples.Library object: both come from the same classes.
        val modelResponse = client.generate(input, getLibrarySchema())
        println("Model response: $modelResponse")

        Json.decodeFromString(modelResponse)
    }

    // Typed objects from here on, no JSON handling.
    library.books.forEach { book ->
        val rating = book.rating?.let { "rated $it" } ?: "no rating"
        val tags = book.tags.joinToString { it.name }
        println("${book.title} by ${book.authors.joinToString()}, $rating. Tags: $tags")
    }
}
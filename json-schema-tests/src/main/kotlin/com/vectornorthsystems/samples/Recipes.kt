package com.vectornorthsystems.samples

import com.vectornorthsystems.jsonschema.SchemaDescription
import com.vectornorthsystems.jsonschema.SchemaRoot
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json

@Serializable
data class Ingredient(
    @SchemaDescription("Name of the ingredient.")
    val name: String,

    @SchemaDescription("The attributes of the ingredient.")
    val quantity: String,
)

@Serializable
enum class Chef {
    ANTHONY, JOHN, PEPE
}

@Serializable
@SchemaRoot
data class DeliciousRecipe(
    @SchemaDescription("The name of the recipe.")
    val name: String,

    @SchemaDescription("Optional time in minutes to prepare the recipe.")
    val prepTimeMinutes: Int = 0,

    val chef: Chef?,

    val ingredients: List<Ingredient>,

    val instructions: List<String>
)

/**
 * An example of the whole round trip with Gemini structured output: it sends the schema of [DeliciousRecipe] as the
 * response format, and decodes the reply straight back into a [DeliciousRecipe].
 *
 * Shows a nullable enum: the input doesn't say who the chef is, so the model answers null for [DeliciousRecipe.chef].
 * The property is required, so it must be present, and nullable, so null is among the values of its enum.
 *
 * Run it with a Gemini API key:
 *   GEMINI_API_KEY=... ./gradlew :json-schema-tests:run --args="recipe"
 */
suspend fun extractRecipe(model: Model) {
    // Generated by the processor from the @SchemaRoot annotation on DeliciousRecipe.
    println("The DeliciousRecipe class JSON schema is: ${DeliciousRecipeSchema.GEMINI}")

    // Adapted from the Gemini API structured output docs
    // (https://ai.google.dev/gemini-api/docs/structured-output#json-schema-support), whose code samples are licensed
    // under the Apache License 2.0 (https://www.apache.org/licenses/LICENSE-2.0).
    // Modified: the input is no longer a quoted JSON string, and says the chef is unknown.
    val input = """
        Please extract the recipe from the following text.
        The recipe doesn't say which chef it comes from.
        The user wants to make delicious chocolate chip cookies.
        They need 2 and 1/4 cups of all-purpose flour, 1 teaspoon of baking soda,
        1 teaspoon of salt, 1 cup of unsalted butter (softened), 3/4 cup of granulated sugar,
        3/4 cup of packed brown sugar, 1 teaspoon of vanilla extract, and 2 large eggs.
        For the best part, they will need 2 cups of semisweet chocolate chips.
        First, preheat the oven to 375°F (190°C). Then, in a small bowl, whisk together the flour,
        baking soda, and salt. In a large bowl, cream together the butter, granulated sugar, and brown sugar
        until light and fluffy. Beat in the vanilla and eggs, one at a time. Gradually beat in the dry
        ingredients until just combined. Finally, stir in the chocolate chips. Drop by rounded tablespoons
        onto ungreased baking sheets and bake for 9 to 11 minutes.
    """.trimIndent()

    // The schema goes out and the answer comes back as a DeliciousRecipe: both come from the same classes.
    val modelResponse = model.generate(input, DeliciousRecipeSchema.GEMINI)
    println("Model response: $modelResponse")

    val recipe = Json.decodeFromString<DeliciousRecipe>(modelResponse)

    // Typed objects from here on, no JSON handling.
    println(
        "Get your delicious ${recipe.name} done in ${recipe.prepTimeMinutes} minutes " +
                "by following ${recipe.instructions.size} simple steps."
    )

    // No chef is named, so the nullable enum comes back as null.
    recipe.chef.shouldBeNull()
}
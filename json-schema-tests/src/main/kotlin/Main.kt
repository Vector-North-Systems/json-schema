import com.vectornorthsystems.jsonschema.*
import io.ktor.client.*
import io.ktor.client.call.*
import io.ktor.client.engine.java.*
import io.ktor.client.request.*
import io.ktor.client.statement.*
import io.ktor.http.*


/*
 * An example of using a generated schema with Gemini structured output: main() prints the schema of [Library],
 * sends it as the response format of a Gemini request, and prints the reply, whose text is JSON matching the schema.
 *
 * Run it with a Gemini API key:
 *   GEMINI_API_KEY=... ./gradlew :json-schema-tests:run
 *
 * The classes below, from the simplest to the one used in main(), show what the annotations do. Edit them and run
 * main() to see the schema and how Gemini follows it. Fixtures that the tests check belong in the `fixtures` package
 * instead.
 */

/**
 * The simplest case: @SchemaRoot makes the processor generate `getSimpleBookSchema()`.
 * Both properties have no default value and are not nullable, so both are required.
 */
@SchemaRoot
data class SimpleBook(
    val title: String,
    val author: String
)

/**
 * A property with a default value is optional: it is left out of the schema's `required` list.
 */
@SchemaRoot
data class AnonymousBook(
    val title: String,
    // A default value makes the property optional.
    val author: String = "Anonymous"
)

/**
 * [SchemaRequired] overrides the rule above: the property has a default value but is still listed as required.
 */
@SchemaRoot
data class AnonymousBookRequired(
    val title: String,
    // A default value makes the property optional, yet the annotation forces it to be required.
    @SchemaRequired
    val author: String = "Anonymous"
)

/**
 * A nullable type becomes a schema type that also accepts `null`. The property has no default value, so it is
 * still required: the model must send the key, and its value may be `null`.
 */
@SchemaRoot
data class BookNullable(
    val title: String?,
)

/**
 * A nullable property with a default value is optional. [SchemaRequired] makes it required, so the model must
 * always send the key, with either a value or `null`.
 */
@SchemaRoot
data class SimpleBoardGameNullableRequired(
    @SchemaRequired
    val name: String? = null,
)

/**
 * The root used by main(). Its schema references [Book], which needs no @SchemaRoot of its own: the processor
 * follows property types, including the elements of a list.
 */
@SchemaRoot
data class Library(
    val books: List<Book>,
)

/**
 * Shows the constraint annotations, and a nested class ([BookTags]) inside a list.
 */
data class Book(
    @SchemaDescription("The title of the book")
    val title: String,

    // At most 3 authors.
    @SchemaMaxItems(3)
    val authors: List<String> = emptyList(),

    // Required despite the default value, with at most 5 tags.
    @SchemaRequired
    @SchemaMaxItems(5)
    val tags: List<BookTags> = emptyList(),

    // The rating must be between 1.0 and 5.0.
    @SchemaMinimum(1.0)
    @SchemaMaximum(5.0)
    val rating: Double = 0.0,
)

/**
 * A tag of a [Book]. The description tells the model what to put in the property.
 */
data class BookTags(
    @SchemaDescription("Tags that can be applied to a book, for example: Fiction, History, Programming, etc")
    val name: String,
)

suspend fun main() {
    // Generated by the processor from the @SchemaRoot annotation on Library.
    val librarySchema = getLibrarySchema()
    println("The Library class JSON schema is: $librarySchema")

    // Written by hand as a JSON string body
    val input =
        """Let's classify the following books using the supplied response format:\nBrave New World is a dystopian science fiction novel by Aldous Huxley. It has a rating of 3.98 on Goodreads.com.\nThe Odyssey tells the story of Odysseus's return to Ithaca after the Trojan War. It is a classic of fiction by Homer. Among its many translations, the English version by Robert Fagles is rated 3.86 on Goodreads.com.\nThe Metamorphosis is a story by Franz Kafka, in which the fictional Gregor Samsa wakes one morning from a dream to find himself transformed into a gigantic insect."""

    // use {} closes the client when done, so the JVM can exit.
    HttpClient(Java).use { client ->
        val response = client.post("https://generativelanguage.googleapis.com/v1beta/interactions") {
            headers {
                append(HttpHeaders.ContentType, ContentType.Application.Json)
                append(
                    "x-goog-api-key",
                    System.getenv("GEMINI_API_KEY") ?: throw IllegalArgumentException("Gemini API key required!")
                )
            }
            // The schema goes in as is: the generated function returns it as a JSON string.
            setBody(
                """
                {
                    "model": "gemini-3.8-flash",
                    "input": "$input",
                    "response_format": $librarySchema
                }
                """.trimIndent()
            )
        }

        if (response.status.isSuccess()) {
            println("Successful response:")

            val stringBody: String = response.body()

            println(stringBody)
            /*
             * An example response, trimmed. The `text` of the model output is the generated output, as JSON that
            [{"text":"{\"books\":[{\"title\":\"Brave New World\",\"tags\":[{\"name\":\"Dystopian\"},{\"name\":\"Science Fiction\"},{\"name\":\"Fiction\"}],\"authors\":[\"Aldous Huxley\"],\"rating\":3.98},{\"title\":\"The Odyssey\",\"tags\":[{\"name\":\"Fiction\"},{\"name\":\"Classic\"},{\"name\":\"Mythology\"}],\"authors\":[\"Homer\",\"Robert Fagles\"],\"rating\":3.86},{\"title\":\"The Metamorphosis\",\"tags\":[{\"name\":\"Fiction\"},{\"name\":\"Classics\"}],\"authors\":[\"Franz Kafka\"]}]}","type":"text"}]
            */
        } else {
            println("Failed response: ${response.bodyAsText()}")
        }
    }
}
